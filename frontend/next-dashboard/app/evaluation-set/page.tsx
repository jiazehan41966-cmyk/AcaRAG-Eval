"use client";

import { useMemo, useState } from "react";

const API_BASE = process.env.NEXT_PUBLIC_API_BASE || "http://localhost:8000";

type GoldenCase = {
  question: string;
  ground_truth: string;
  supporting_evidence: string[];
  expected_citation: string[];
  difficulty: string;
  question_type: string;
};

export default function EvaluationSetPage() {
  const [cases, setCases] = useState<GoldenCase[]>([]);
  const [status, setStatus] = useState("Load a JSONL file generated by scripts/generate_pdf_golden_set.py");

  const summary = useMemo(() => {
    const byType = cases.reduce<Record<string, number>>((acc, item) => {
      acc[item.question_type] = (acc[item.question_type] || 0) + 1;
      return acc;
    }, {});
    const withEvidence = cases.filter((item) => item.supporting_evidence?.length).length;
    const withCitation = cases.filter((item) => item.expected_citation?.length).length;
    return { byType, withEvidence, withCitation };
  }, [cases]);

  function onFile(file: File | undefined) {
    if (!file) return;
    const reader = new FileReader();
    reader.onload = () => {
      const text = String(reader.result || "");
      const rows = text
        .split(/\r?\n/)
        .map((line) => line.trim())
        .filter(Boolean)
        .map((line) => JSON.parse(line) as GoldenCase);
      setCases(rows);
      setStatus(`Loaded ${rows.length} cases from ${file.name}`);
    };
    reader.readAsText(file);
  }

  async function runEval() {
    setStatus("Submitting evaluation run...");
    const res = await fetch(`${API_BASE}/api/eval/run`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        run_name: `next_dashboard_eval_${Date.now()}`,
        question_set: cases,
        top_k: 5,
        run_ragas: false,
        run_deepeval: false
      })
    });
    const payload = await res.json();
    setStatus(`Run ${payload.run_id || payload.task_id || "unknown"}: ${payload.status}`);
  }

  return (
    <div className="stack">
      <section className="panel">
        <p className="muted">Golden Set Manager</p>
        <h1>Curate grounded evaluation cases.</h1>
        <p className="muted">
          Load JSONL locally, inspect evidence/citation coverage, then trigger a lightweight evaluation run.
        </p>
        <div className="toolbar">
          <input type="file" accept=".jsonl,.json" onChange={(event) => onFile(event.target.files?.[0])} />
          <button disabled={!cases.length} onClick={() => void runEval()}>
            Run lightweight eval
          </button>
        </div>
        <p className="muted">{status}</p>
      </section>

      <section className="grid">
        <div className="metric">
          <span className="muted">Cases</span>
          <strong>{cases.length}</strong>
        </div>
        <div className="metric">
          <span className="muted">With evidence</span>
          <strong>{summary.withEvidence}</strong>
        </div>
        <div className="metric">
          <span className="muted">With citations</span>
          <strong>{summary.withCitation}</strong>
        </div>
      </section>

      <section className="panel">
        <h2>Question Type Distribution</h2>
        <pre>{JSON.stringify(summary.byType, null, 2)}</pre>
      </section>

      <section className="panel">
        <h2>Cases</h2>
        <table>
          <thead>
            <tr>
              <th>Type</th>
              <th>Question</th>
              <th>Evidence</th>
              <th>Citation</th>
            </tr>
          </thead>
          <tbody>
            {cases.slice(0, 80).map((item, idx) => (
              <tr key={`${item.question}-${idx}`}>
                <td>{item.question_type}</td>
                <td>{item.question}</td>
                <td>{item.supporting_evidence?.join(", ")}</td>
                <td>{item.expected_citation?.join(", ")}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </section>
    </div>
  );
}
